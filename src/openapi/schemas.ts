// The document's schemas. Upstream's docs/swagger/collections.yaml is where the ported ones started;
// each is corrected to what the server answers, which the OpenAPI contract checks.
export type Schema = Record<string, unknown>;

const string = { type: "string" };
const integer = { type: "integer" };
const number = { type: "number" };
const boolean = { type: "boolean" };
const time = { type: "string", format: "date-time" };
const uuid = { type: "string", format: "uuid" };
/** A free-form JSON object. */
export const free = { type: "object", additionalProperties: true };

export const ref = (name: string): Schema => ({ $ref: `#/components/schemas/${name}` });
export const array = (items: Schema): Schema => ({ type: "array", items });
export const nullable = (schema: Schema): Schema =>
  schema.$ref !== undefined || schema.oneOf !== undefined
    ? { anyOf: [schema, { type: "null" }] }
    : { ...schema, type: [schema.type, "null"] };
const choice = (...values: string[]): Schema => ({ type: "string", enum: values });
/** Every property is required unless it is named in `optional`. */
export const object = (properties: Record<string, Schema>, optional: string[] = []): Schema => ({
  type: "object",
  properties,
  required: Object.keys(properties).filter((name) => !optional.includes(name)),
});
const map = (value: Schema): Schema => ({ type: "object", additionalProperties: value });
/** A write body: nothing is required unless it is named. */
const input = (properties: Record<string, Schema>, required: string[] = []): Schema => ({
  type: "object",
  properties,
  ...(required.length ? { required } : {}),
});
/** The paged collection of `item`. Upstream's collections also echo `search` and `query`. */
export const page = (item: Schema, echoed = false): Schema =>
  object({
    results: array(item),
    ...(echoed ? { search: string, query: string } : {}),
    total: integer,
    per_page: { ...integer, description: "0 for `per_page=all`." },
    page: integer,
  });

