// Every documented route. Upstream's docs/swagger/collections.yaml is the starting point for the
// ported ones; `native` marks those listmonk does not have.
import { array, free, nullable, object, page, ref, type Schema } from "@/openapi/schemas";

export interface Parameter {
  name: string;
  schema?: Schema;
  required?: boolean;
  description?: string;
}
export interface Operation {
  route: string;
  id: string;
  tag: string;
  summary: string;
  description?: string;
  /** Upstream has no such endpoint. */
  native?: boolean;
  /** No credential is needed. */
  anonymous?: boolean;
  /** A browser session only: API credentials are refused. */
  session?: boolean;
  /** Any one of these; the first is the one a refusal names. */
  permissions?: string[];
  query?: Parameter[];
  /** A JSON schema, or a named media type with its schema. */
  body?: Schema;
  bodyType?: string;
  /** The `data` of a 200 envelope, unless `answer` replaces it. */
  data?: Schema;
  /** A whole 200 answer that has no envelope, by media type. */
  answer?: Record<string, Schema>;
  /** Refusals worth naming, on top of 400 for a bad ID and 403 for a missing credential. */
  errors?: number[];
}

