export function simpleLower(input: string): string {
  let result = "";
  for (const char of input) {
    const code = char.codePointAt(0)!;
    let low = 0,
      high = ranges.length,
      mapped = code;
    while (low < high) {
      const middle = (low + high) >>> 1;
      const [start, end, delta] = ranges[middle]!;
      if (code < start) high = middle;
      else if (code > end) low = middle + 1;
      else {
        mapped = delta === null ? start + (((code - start) & ~1) | 1) : code + delta;
        break;
      }
    }
    result += String.fromCodePoint(mapped);
  }
  return result;
}
