function titleRune(value: string): string {
  const code = value.codePointAt(0)!;
  const expanded = full.get(code);
  if (expanded !== undefined) {
    return expanded;
  }
  let lo = 0,
    hi = ranges.length;
  while (lo < hi) {
    const mid = (lo + hi) >>> 1;
    const [start, end, delta] = ranges[mid]!;
    if (code < start) {
      hi = mid;
    } else if (code > end) {
      lo = mid + 1;
    } else {
      return String.fromCodePoint(delta === null ? start + ((code - start) & ~1) : code + delta);
    }
  }
  return value;
}

