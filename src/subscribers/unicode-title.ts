function contains(ranges: readonly number[], code: number): boolean {
  let lo = 0,
    hi = ranges.length / 2;
  while (lo < hi) {
    const mid = (lo + hi) >>> 1;
    if (code < ranges[mid * 2]!) hi = mid;
    else if (code > ranges[mid * 2 + 1]!) lo = mid + 1;
    else return true;
  }
  return false;
}

// Port of x/text v0.42.0 cases/map.go's titleCaser after listmonk's
// simple-lowercase email normalization. All subsequent cased runes are
// already lower; only each word's first cased rune needs a full title map.
export function titleWords(value: string): string {
  let inWord = false,
    previousMid = false,
    result = "";
  for (const char of value) {
    const code = char.codePointAt(0)!;
    const mid = contains(mids, code);
    if (previousMid && mid) inWord = false;
    if (contains(cased, code)) {
      result += inWord ? char : titleRune(char);
      inWord = true;
    } else {
      result += char;
      if (!mid && !contains(letters, code)) inWord = false;
    }
    previousMid = mid;
  }
  return result;
}
